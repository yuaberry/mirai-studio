/**
 * PublishStore — the disk-backed registry of published anime projects.
 *
 * Storage layout, one directory per project:
 *
 *   <root>/<id>/manifest.json     the PublishManifest (author + facts)
 *   <root>/<id>/bundle.zip        the project folder, zipped
 *   <root>/<id>/.token            the publisher's token (who may delete)
 *
 * The store is transport-free (it takes no HTTP object), so the HTTP layer and
 * the tests exercise the SAME rules. Nothing here trusts a client: the token is
 * compared in constant time, the id is validated to a charset, and the bundle
 * is streamed to disk rather than buffered in memory.
 */
import { createHash } from 'node:crypto'
import {
  existsSync,
  mkdirSync,
  readFileSync,
  writeFileSync,
  rmSync,
  readdirSync,
  renameSync,
  statSync,
  createWriteStream,
} from 'node:fs'
import { join } from 'node:path'
import { PublishManifest, type PublishManifest as PublishManifestType } from '@mirai/shared'

/** Ids are short, url-safe and generated by the server (never by a client). */
const ID_ALPHABET = '0123456789abcdefghijklmnopqrstuvwxyz'
const ID_LENGTH = 12

export interface PublishStoreOptions {
  /** Root directory where published projects live. */
  root: string
  /** Maximum size of one published bundle, in bytes. */
  maxBundleBytes?: number
}

function randomId(): string {
  const bytes = new Uint8Array(ID_LENGTH)
  crypto.getRandomValues(bytes)
  let out = ''
  for (const b of bytes) out += ID_ALPHABET[b % ID_ALPHABET.length]
  return out
}

function tokenOf(): string {
  return randomId() + randomId()
}

/** A published project, as the store returns it. */
export interface StoredProject {
  manifest: PublishManifestType
  /** Absolute path of the bundle zip. */
  bundlePath: string
}

export class PublishStore {
  private readonly maxBundleBytes: number

  constructor(private readonly opts: PublishStoreOptions) {
    this.maxBundleBytes = opts.maxBundleBytes ?? 2 * 1024 ** 3
    mkdirSync(opts.root, { recursive: true })
  }

  get root(): string {
    return this.opts.root
  }

  /** Lists every published project, newest first. */
  list(): StoredProject[] {
    const out: StoredProject[] = []
    for (const entry of readdirSync(this.opts.root)) {
      const manifestPath = join(this.opts.root, entry, 'manifest.json')
      const bundlePath = join(this.opts.root, entry, 'bundle.zip')
      if (!existsSync(manifestPath) || !existsSync(bundlePath)) continue
      try {
        out.push({
          manifest: PublishManifest.parse(JSON.parse(readFileSync(manifestPath, 'utf8'))),
          bundlePath,
        })
      } catch {
        // A malformed manifest is skipped, never fatal to the whole listing.
      }
    }
    return out.sort((a, b) => (a.manifest.publishedAt < b.manifest.publishedAt ? 1 : -1))
  }

  get(id: string): StoredProject | null {
    if (!isId(id)) return null
    const dir = join(this.opts.root, id)
    const manifestPath = join(dir, 'manifest.json')
    const bundlePath = join(dir, 'bundle.zip')
    if (!existsSync(manifestPath) || !existsSync(bundlePath)) return null
    try {
      return {
        manifest: PublishManifest.parse(JSON.parse(readFileSync(manifestPath, 'utf8'))),
        bundlePath,
      }
    } catch {
      return null
    }
  }

  /**
   * Writes a published bundle and its manifest.
   *
   * The bundle is STREAMED to a temp file and hashed while it lands, so an
   * oversized upload is rejected without buffering it in memory. The checksum
   * in the manifest is the server's own measurement, not the client's claim.
   */
  async publish(
    input: {
      title: string
      tagline?: string
      tags?: string[]
      medium?: string
      author: PublishManifestType['author']
      totalBytes: number
      /**
       * The zip bytes, as anything the store can ITERATE. The store only
       * ever does `for await (const chunk of bundle)`, so the type says
       * exactly that — it used to claim `NodeJS.ReadableStream`, which is
       * narrower than the real contract and rejected a perfectly valid
       * async generator in the tests.
       */
      bundle: AsyncIterable<Uint8Array> | Buffer
      /** Handle of the publishing account, when the client has a session. */
      owner?: string | null
    },
  ): Promise<{ id: string; token: string; manifest: PublishManifestType }> {
    if (input.title.trim().length === 0) throw new Error('A title is required.')
    if (input.totalBytes > this.maxBundleBytes) {
      throw new Error(
        `The bundle is ${(input.totalBytes / 1024 / 1024).toFixed(1)} MB — the server allows ${(this.maxBundleBytes / 1024 / 1024).toFixed(0)} MB.`,
      )
    }

    const id = randomId()
    const dir = join(this.opts.root, id)
    mkdirSync(dir, { recursive: true })

    // Land the bundle at a temp name, hash it, then promote it — a partial
    // upload must never become a downloadable project.
    const tempPath = join(dir, 'bundle.tmp')
    const hash = createHash('sha256')
    let written = 0

    if (Buffer.isBuffer(input.bundle)) {
      written = input.bundle.byteLength
      if (written > this.maxBundleBytes) {
        rmSync(dir, { recursive: true, force: true })
        throw new Error('The bundle exceeds the server limit.')
      }
      hash.update(input.bundle)
      writeFileSync(tempPath, input.bundle)
    } else {
      const stream = createWriteStream(tempPath)
      try {
        for await (const chunk of input.bundle) {
          const buf = Buffer.isBuffer(chunk) ? chunk : Buffer.from(chunk)
          written += buf.byteLength
          if (written > this.maxBundleBytes) {
            stream.destroy()
            rmSync(dir, { recursive: true, force: true })
            throw new Error('The bundle exceeds the server limit.')
          }
          hash.update(buf)
          if (!stream.write(buf)) {
            // Backpressure: wait for drain so the guard keeps pace with bytes.
            await new Promise<void>((resolve, reject) => {
              stream.once('drain', resolve)
              stream.once('error', reject)
            })
          }
        }
        await new Promise<void>((resolve, reject) => {
          stream.once('error', reject)
          stream.end(() => resolve())
        })
      } catch (err) {
        stream.destroy()
        rmSync(dir, { recursive: true, force: true })
        throw err
      }
    }

    const checksum = hash.digest('hex')
    const now = new Date().toISOString()
    const manifest = PublishManifest.parse({
      id,
      title: input.title.trim(),
      tagline: input.tagline ?? '',
      author: input.author,
      tags: input.tags ?? [],
      medium: input.medium ?? 'ANIME',
      checksum,
      fileCount: 0,
      totalBytes: written,
      publishedAt: now,
      updatedAt: now,
      downloads: 0,
      owner: input.owner ?? null,
    })

    writeFileSync(join(dir, 'manifest.json'), JSON.stringify(manifest, null, 2))
    const token = tokenOf()
    writeFileSync(join(dir, '.token'), token, { encoding: 'utf8', mode: 0o600 })
    // Promote the verified bundle.
    renameSync(tempPath, join(dir, 'bundle.zip'))

    return { id, token, manifest }
  }

  /** Counts a download (the only social signal the app shows). */
  countDownload(id: string): PublishManifestType | null {
    const stored = this.get(id)
    if (!stored) return null
    const manifest = PublishManifest.parse({
      ...stored.manifest,
      downloads: stored.manifest.downloads + 1,
      updatedAt: new Date().toISOString(),
    })
    writeFileSync(join(this.opts.root, id, 'manifest.json'), JSON.stringify(manifest, null, 2))
    return manifest
  }

  /**
   * Deletes a published project. The token MUST match — a wrong token deletes
   * nothing and reports exactly that, so the UI can say so.
   */
  remove(id: string, token: string): { ok: boolean; message: string } {
    if (!isId(id)) return { ok: false, message: 'Unknown project.' }
    const stored = this.get(id)
    if (!stored) return { ok: false, message: 'Unknown project.' }
    const expected = readFileSync(join(this.opts.root, id, '.token'), 'utf8')
    if (!timingSafeEqual(expected, token)) {
      return { ok: false, message: 'That token does not match — nothing was deleted.' }
    }
    rmSync(join(this.opts.root, id), { recursive: true, force: true })
    return { ok: true, message: `"${stored.manifest.title}" removed.` }
  }

  /**
   * Removes EVERY project an account owns — the revocation a user asks for
   * when a laptop is lost or an account is compromised.
   */
  removeByOwner(handle: string): { removed: number } {
    let removed = 0
    for (const stored of this.list()) {
      if (stored.manifest.owner !== handle) continue
      rmSync(join(this.opts.root, stored.manifest.id), { recursive: true, force: true })
      removed += 1
    }
    return { removed }
  }

  /** Projects an account owns (for the account page). */
  listByOwner(handle: string): PublishManifestType[] {
    return this.list()
      .map((s) => s.manifest)
      .filter((m) => m.owner === handle)
  }

  /** The bundle's size, or -1 when it is gone. */
  bundleSize(id: string): number {
    const stored = this.get(id)
    if (!stored) return -1
    return statSync(stored.bundlePath).size
  }
}

function isId(id: string): boolean {
  return /^[0-9a-z]{12}$/.test(id)
}

function timingSafeEqual(a: string, b: string): boolean {
  if (a.length !== b.length) return false
  let diff = 0
  for (let i = 0; i < a.length; i += 1) diff |= a.charCodeAt(i) ^ b.charCodeAt(i)
  return diff === 0
}