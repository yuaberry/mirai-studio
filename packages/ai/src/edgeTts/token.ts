/**
 * Edge TTS Sec-MS-GEC v2 token (ported from the reference implementation).
 *
 * WHY A PORT AND NOT AN HTTP CALL
 * -------------------------------
 * Microsoft's online (keyless) TTS endpoint authenticates EVERY request —
 * the voice list AND the synthesis socket — with a `Sec-MS-GEC` header.
 * The token is derived from the CLOCK, not from a session: no key to
 * refresh, no login, nothing that can "expire". That property is what
 * makes Edge TTS viable as a free, permanent voice path for the studio,
 * and this module is that derivation.
 *
 * HONESTY NOTE: v1 of this token (a plain SHA-256 of
 * `trustedClientToken + ticks`) stopped being accepted when the endpoint
 * moved to Edge 143. The current token is a SHA-256 with MODIFIED round
 * constants, seeded by a custom state, followed by a "CS64" checksum,
 * hashed together as `<16 hex>-<64 hex>`. The algorithm is reproduced
 * here and PINNED BY TESTS against values generated by the authoritative
 * implementation — a silent drift in this port would break every voice in
 * the app, so it fails loudly in the tests instead of in a user's hand.
 *
 * CLOCK SKEW: a machine whose clock is off gets rejected (403). The
 * provider reads the server's `Date` header and re-issues — see
 * `adjustClockSkewSeconds`.
 */

/**
 * The trusted-client token is PUBLIC by design (it ships inside every Edge
 * browser); the security model is the clock-derived Sec-MS-GEC.
 */
export const TRUSTED_CLIENT_TOKEN = '6A5AA1D4EAFF4E9FB37E23D68491D6F4'

/**
 * The Chromium/Edge version the client impersonates. The endpoint pins
 * `Sec-MS-GEC-Version` to `2-<version>` and rejects unknown versions —
 * updated alongside the endpoint's expectations.
 */
export const CHROMIUM_FULL_VERSION = '143.0.3650.75'
export const SEC_MS_GEC_VERSION = `2-${CHROMIUM_FULL_VERSION}`

/** Seconds between the Windows file-time epoch (1601-01-01) and the Unix epoch. */
export const WIN_EPOCH = 11644473600

// ---------------------------------------------------------------- primitives

const MASK = 0xffffffff
const imul = (a: number, b: number): number => Math.imul(a, b) >>> 0
const add = (a: number, b: number): number => ((a + b) >>> 0)
/** Rotate right (the reference writes `(word * (2**32+1)) >> k`, which is ROTR for 0<k<32). */
const rotr = (word: number, k: number): number => ((word >>> k) | (word << (32 - k))) >>> 0
const rol16 = (value: number): number => ((value << 16) | (value >>> 16)) >>> 0

const BE32 = (b0: number, b1: number, b2: number, b3: number): number =>
  (((b0 << 24) | (b1 << 16) | (b2 << 8) | b3) >>> 0)

const toHex = (bytes: Uint8Array): string =>
  Array.from(bytes, (b) => b.toString(16).padStart(2, '0')).join('').toUpperCase()

